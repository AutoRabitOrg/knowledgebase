#!/bin/sh
# Standardize release notes and open a pull request, safely and repeatably.
#
#   tools/release-notes/run.sh            # all products
#   tools/release-notes/run.sh Vault      # one product (ARM, DataLoader, CodeScan,
#                                         #   "CodeScan Self-Hosted", Vault, Guard, nCino, "IZ Suite")
#
# What it does, in order. It stops at the first problem and changes nothing on GitHub.
#   1. Starts from the latest main, in a temporary copy (your folder isn't touched).
#   2. Standardizes the release notes (formatting only).
#   3. Proves no wording, link or date changed (verify.py).
#   4. Runs the repository checks (.github/scripts/check_docs.py).
#   5. Shows a summary and asks before pushing a branch and opening a pull request.
set -eu
PRODUCT="${1:-all}"
REPO="$(git rev-parse --show-toplevel)"
TOOLS="$REPO/tools/release-notes"
STAMP="$(date +%Y%m%d-%H%M)"
SLUG="$(printf '%s' "$PRODUCT" | tr 'A-Z ' 'a-z-')"
BRANCH="release-notes/standardize-$SLUG-$STAMP"
WORK="$(mktemp -d)/kb"
OUT="$HOME/release-notes-runs/$STAMP-$SLUG"
mkdir -p "$OUT"

echo "1/5  Getting the latest main"
git -C "$REPO" fetch -q origin main
git -C "$REPO" worktree add -q --no-checkout -b "$BRANCH" "$WORK" origin/main
PUSHED=0
cleanup() {
  git -C "$REPO" worktree remove --force "$WORK" 2>/dev/null || true
  [ "$PUSHED" = 1 ] || git -C "$REPO" branch -q -D "$BRANCH" 2>/dev/null || true
}
trap cleanup EXIT
cd "$WORK"
git sparse-checkout set --no-cone '/*' '!/.gitbook/assets/'   # skip ~2 GB of images
git checkout -q

echo "2/5  Standardizing release notes: $PRODUCT"
python3 -I "$TOOLS/standardize.py" "$PRODUCT" "$OUT/needs-a-person.csv"
if git diff --quiet; then echo "Nothing to change: the release notes already follow the standard."; exit 0; fi
git add -A
git commit -q -m "Standardize $PRODUCT release notes formatting" \
  -m "Generated by tools/release-notes/run.sh from $(git rev-parse --short origin/main). Formatting only; verify.py confirmed no wording, links or dates changed."

echo "3/5  Proving nothing was lost"
if ! python3 -I "$TOOLS/verify.py" origin/main HEAD "$OUT/review.csv"; then
  echo "Stopped: the check above found a content change. Nothing was pushed."; exit 1
fi

echo "4/5  Running the repository checks"
if [ -f "$REPO/.github/scripts/check_docs.py" ]; then
  python3 -I "$REPO/.github/scripts/check_docs.py" pr origin/main HEAD > "$OUT/checks.txt" || {
    grep -E '^::error' "$OUT/checks.txt" | sed 's/^::error file=\([^,]*\),line=\([0-9]*\)::/  \1:\2  /'
    echo "Stopped: the repository checks failed. Nothing was pushed."; exit 1; }
  tail -n 1 "$OUT/checks.txt"
fi

echo "5/5  Summary"
git diff --shortstat origin/main HEAD
echo "  Every changed heading and date, for a quick skim: $OUT/review.csv"
echo "  Items it left for a person to fix:                $OUT/needs-a-person.csv"
printf "Push branch %s and open a pull request? [y/N] " "$BRANCH"
read -r ok
case "$ok" in y|Y|yes) ;; *) echo "Not pushed. Run again whenever you're ready."; exit 0;; esac
git push -q origin "HEAD:refs/heads/$BRANCH"
PUSHED=1
STATS="$(python3 -I "$TOOLS/verify.py" origin/main HEAD | head -n 1)"
gh pr create --base main --head "$BRANCH" --title "Standardize $PRODUCT release notes formatting" --body "Generated by \`tools/release-notes/run.sh $PRODUCT\` from main at \`$(git rev-parse --short origin/main)\`.

**Formatting only.** $STATS \`verify.py\` confirmed every body line is unchanged, every heading keeps its version number, and every date keeps its day, month and year. Links to renamed headings were updated.

**Before merging:** merge within a day or so. If GitBook edits the same pages first, close this PR and run the script again; it takes about a minute.

Items left for a person to fix are listed in \`needs-a-person.csv\` from the run."
